import { describe, it, expect, vi, beforeAll } from 'vitest';
import { execFileSync, spawnSync } from 'child_process';
import * as fs from 'fs';
import { SlideService } from './slide.service';

/**
 * Full-pipeline test with REAL fs, real ffmpeg, and real music-metadata —
 * only the AI/provider seams (defaults resolution, AI calls, job lifecycle)
 * are mocked. The image artifact is a data: URI (the OpenRouter prod case),
 * so no network is touched.
 *
 * Skips when no ffmpeg binary is available (CI runners without ffmpeg): the
 * mocked-unit suite in slide.service.spec.ts still covers the logic there.
 */

// Mirrors SlideService's own getFfmpegPath resolution.
function findFfmpeg(): string | null {
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const staticPath = require('ffmpeg-static') as string | undefined;
    if (staticPath && fs.existsSync(staticPath)) return staticPath;
  } catch {}
  const which = spawnSync('which', ['ffmpeg']);
  if (which.status === 0) return which.stdout.toString().trim().split('\n')[0];
  return null;
}

const FFMPEG = findFfmpeg();
const HAS_FFPROBE = spawnSync('which', ['ffprobe']).status === 0;

// 64x64 solid red PNG (even dimensions for yuv420p).
const PNG_BASE64 =
  'iVBORw0KGgoAAAANSUhEUgAAAEAAAABACAIAAAAlC+aJAAAACXBIWXMAAAABAAAAAQBPJcTWAAAAcElEQVR4nO3PAQkAAAyEwO/febAYIggXQHebGl/QgBxf0IAcX9CAHF/QgBxf0IAcX9CAHF/QgBxf0IAcX9CAHF/QgBxf0IAcX9CAHF/QgBxf0IAcX9CAHF/QgBxf0IAcX9CAHF/QgBxf0IAcX9CA3ANcoNDiu2vTdwAAAABJRU5ErkJggg==';

describe.skipIf(!FFMPEG)('SlideService — real ffmpeg pipeline', () => {
  let audioBuffer: Buffer;

  beforeAll(() => {
    // A real 1-second audio file, generated by the same ffmpeg the service uses.
    const tonePath = `${fs.mkdtempSync('/tmp/slide-spec-')}/tone.mp3`;
    execFileSync(FFMPEG!, [
      '-hide_banner', '-loglevel', 'error', '-y',
      '-f', 'lavfi', '-i', 'sine=frequency=440:duration=1',
      tonePath,
    ]);
    audioBuffer = fs.readFileSync(tonePath);
  }, 30_000);

  function makeService(captured: { buffer?: Buffer; mime?: string }) {
    const defaultsResolution = {
      resolve: vi.fn().mockImplementation((_d: string, category: string) => {
        if (category === 'image-slide') {
          return Promise.resolve({ providerId: 'openrouter', version: 'v1', model: 'm', source: 'stored' });
        }
        if (category === 'high-reasoning') {
          return Promise.resolve({ providerId: 'openai', version: 'v1', model: 'o3-mini', source: 'stored' });
        }
        return Promise.resolve(null);
      }),
    };
    const aiDefaults = {
      highReasoningText: vi.fn().mockResolvedValue(
        JSON.stringify([
          { script: 'First slide narration.', imagePrompt: 'A red square' },
          { script: 'Second slide narration.', imagePrompt: 'Another red square' },
        ]),
      ),
      textToImage: vi.fn().mockResolvedValue(`data:image/png;base64,${PNG_BASE64}`),
    };
    const aiMediaService = {
      listGenerationProviders: vi.fn().mockResolvedValue({
        providers: [{ identifier: 'openai', name: 'OpenAI' }],
        default: { providerId: 'openai', model: 'tts-1' },
      }),
      textToSpeech: vi.fn().mockResolvedValue(audioBuffer),
    };
    const lifecycle = {
      createPendingJob: vi.fn().mockResolvedValue({ id: 'slide-pipeline-1' }),
      completeJobWithBuffer: vi.fn().mockImplementation((_job: unknown, buffer: Buffer, mime: string) => {
        captured.buffer = buffer;
        captured.mime = mime;
        return Promise.resolve(true);
      }),
      getJob: vi.fn().mockResolvedValue({ id: 'slide-pipeline-1', artifactUrl: '/uploads/pipeline.mp4', status: 'completed' }),
      failJob: vi.fn().mockResolvedValue(undefined),
    };
    return new SlideService(defaultsResolution as never, aiDefaults as never, aiMediaService as never, lifecycle as never);
  }

  it('assembles a valid multi-slide mp4 with h264 video and aac audio', async () => {
    const captured: { buffer?: Buffer; mime?: string } = {};
    const service = makeService(captured);

    const result = await service.generateSlide({ orgId: 'org-1', prompt: 'Two slides about red squares' });

    expect(result).toBe('/uploads/pipeline.mp4');
    expect(captured.mime).toBe('video/mp4');
    const buffer = captured.buffer!;
    expect(Buffer.isBuffer(buffer)).toBe(true);
    // ISO BMFF magic: 4-byte size then 'ftyp'.
    expect(buffer.subarray(4, 8).toString('ascii')).toBe('ftyp');

    if (HAS_FFPROBE) {
      const probePath = `${fs.mkdtempSync('/tmp/slide-spec-probe-')}/out.mp4`;
      fs.writeFileSync(probePath, buffer);
      const probe = JSON.parse(
        execFileSync('ffprobe', [
          '-v', 'error', '-print_format', 'json',
          '-show_streams', '-show_format', probePath,
        ]).toString(),
      );
      const codecs = probe.streams.map((s: any) => s.codec_name).sort();
      expect(codecs).toEqual(['aac', 'h264']);
      const video = probe.streams.find((s: any) => s.codec_type === 'video');
      const audio = probe.streams.find((s: any) => s.codec_type === 'audio');
      // Two slides, each held for max(audio≈1s, min 5s) => 10s video timeline.
      // Regression guard: `-r 30` (output option) truncated the video after the
      // first slide, and `-shortest` then cut it to the narration length.
      expect(Number(video.duration)).toBeGreaterThan(9);
      expect(Number(video.duration)).toBeLessThan(12);
      // The narration track ends after the second slide's 1s audio at offset 5s.
      expect(Number(audio.duration)).toBeGreaterThan(5.5);
      expect(Number(audio.duration)).toBeLessThan(6.5);
    }
  }, 60_000);
});
